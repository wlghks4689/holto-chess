import fs from 'node:fs';
import { build } from 'esbuild';
// Offline generation of the R1 "power ranking": all 169 starting hands ordered by equity at an
// eight-handed table (seven random opponents, PORENA's seat count). Run: node tools/generate-preflop-rank.mjs
const bundle = await build({ stdin: { contents: 'export { makeDeck } from "./src/core/poker/cards"; export { scoreSeven } from "./src/game/showdownEquity";', resolveDir: process.cwd(), loader: 'ts' }, bundle: true, write: false, platform: 'node', format: 'esm' });
const { makeDeck, scoreSeven } = await import('data:text/javascript;base64,' + Buffer.from(bundle.outputFiles[0].text).toString('base64'));
const opponents = 7, samples = 400000, chars = '23456789TJQKA', equities = [];
for (let high = 14; high >= 2; high--) for (let low = high; low >= 2; low--) for (const suited of high === low ? [false] : [true, false]) {
  const key = chars[high - 2] + chars[low - 2] + (high === low ? '' : suited ? 's' : 'o');
  const a = { id: chars[high - 2] + 'c', rank: high, suit: 'c' }, b = { id: chars[low - 2] + (suited ? 'c' : 'd'), rank: low, suit: suited ? 'c' : 'd' };
  const pool = makeDeck().filter(c => c.id !== a.id && c.id !== b.id);
  let seed = 2166136261;
  for (const ch of `porena-power-v1:${key}`) seed = Math.imul(seed ^ ch.charCodeAt(0), 16777619);
  const random = () => { seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0; return seed / 4294967296; };
  const need = 5 + 2 * opponents;
  let equity = 0;
  for (let i = 0; i < samples; i++) {
    for (let j = 0; j < need; j++) { const k = j + Math.floor(random() * (pool.length - j)); [pool[j], pool[k]] = [pool[k], pool[j]]; }
    const board = pool.slice(0, 5), hero = scoreSeven([a, b, ...board]);
    let ties = 0, lost = false;
    for (let o = 0; o < opponents && !lost; o++) {
      const score = scoreSeven([pool[5 + 2 * o], pool[6 + 2 * o], ...board]);
      if (score > hero) lost = true; else if (score === hero) ties++;
    }
    if (!lost) equity += 1 / (ties + 1);
  }
  equities.push([key, equity / samples]);
}
const order = equities.sort((x, y) => y[1] - x[1]).map(([key]) => key);
const text = `// Generated by tools/generate-preflop-rank.mjs; ${samples} deterministic deals per hand.\n// The 169 starting hands, best first, by equity against ${opponents} random hands (an eight-handed table).\nexport const PREFLOP_POWER_ORDER: readonly string[] = [\n${Array.from({ length: Math.ceil(order.length / 13) }, (_, row) => '  ' + order.slice(row * 13, row * 13 + 13).map(key => `"${key}"`).join(', ') + ',').join('\n')}\n];\n`;
fs.writeFileSync('src/game/preflopRankData.ts', text);
console.log(JSON.stringify({ hands: order.length, first: order.slice(0, 3), last: order.slice(-3) }));
