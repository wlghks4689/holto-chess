import fs from 'node:fs';
import { build } from 'esbuild';
// Offline generation: runtime AI only reads the table, independently of game RNG.
const bundle = await build({ stdin: { contents: 'export { makeDeck } from "./src/core/poker/cards"; export { scoreSeven } from "./src/game/showdownEquity";', resolveDir: process.cwd(), loader: 'ts' }, bundle: true, write: false, platform: 'node', format: 'esm' });
const { makeDeck, scoreSeven } = await import('data:text/javascript;base64,' + Buffer.from(bundle.outputFiles[0].text).toString('base64'));
const samples = 32768, data = {}, chars = '23456789TJQKA';
for (let high = 14; high >= 2; high--) for (let low = high; low >= 2; low--) for (const suited of high === low ? [false] : [true, false]) {
  const key = chars[high - 2] + chars[low - 2] + (high === low ? '' : suited ? 's' : 'o');
  const first = { id: chars[high - 2] + 'c', rank: high, suit: 'c' };
  const second = { id: chars[low - 2] + (suited ? 'c' : 'd'), rank: low, suit: suited ? 'c' : 'd' };
  const unseen = makeDeck().filter(c => c.id !== first.id && c.id !== second.id);
  let seed = 2166136261;
  for (const ch of `porena-r1-v1:${key}`) seed = Math.imul(seed ^ ch.charCodeAt(0), 16777619);
  const random = () => { seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0; return seed / 4294967296; };
  let equity = 0, win = 0, highWin = 0, lowWin = 0;
  const categories = Array(10).fill(0);
  for (let i = 0; i < samples; i++) {
    const pool = [...unseen];
    for (let j = 0; j < 7; j++) { const k = j + Math.floor(random() * (pool.length - j)); [pool[j], pool[k]] = [pool[k], pool[j]]; }
    const board = pool.slice(2, 7);
    const hero = scoreSeven([first, second, ...board]), opponent = scoreSeven(pool.slice(0, 7));
    categories[hero >= 8 * 16 ** 5 + 14 * 16 ** 4 ? 9 : Math.floor(hero / 16 ** 5)]++;
    equity += hero > opponent ? 1 : hero === opponent ? .5 : 0;
    if (hero > opponent) {
      win++;
      // Count only wins where removing this hole card weakens BEST 5.
      if (scoreSeven([second, ...board]) < hero) highWin++;
      if (scoreSeven([first, ...board]) < hero) lowWin++;
    }
  }
  const fraction = n => Number((n / samples).toFixed(6));
  data[key] = { equity: fraction(equity), win: fraction(win), categories: categories.map(fraction), winWithHigh: fraction(highWin), winWithLow: fraction(lowWin) };
}
const text = `// Generated by tools/generate-r1-preflop.mjs; ${samples} deterministic legal deals per hand.\n// Unknown random opponent, ties count as half a win. No live opponents or future boards are read.\nexport type R1PreflopStats = { equity: number; win: number; categories: readonly number[]; winWithHigh: number; winWithLow: number };\nexport const R1_PREFLOP_SAMPLES = ${samples};\nexport const R1_PREFLOP_STATS: Readonly<Record<string, R1PreflopStats>> = {\n${Object.entries(data).map(([key, value]) => `  "${key}": ${JSON.stringify(value)},`).join('\n')}\n};\n`;
fs.writeFileSync('src/game/r1PreflopData.ts', text);
console.log(JSON.stringify({ hands: Object.keys(data).length, samples, output: 'src/game/r1PreflopData.ts' }));
